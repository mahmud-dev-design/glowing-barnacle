async def deliver(uid, f):
    caption=f"<b>{escape(f['title'])}</b>\n{escape(f['description'] or '')}"
    if f['file_type']=='photo': await bot.send_photo(uid,f['file_id'],caption=caption)
    elif f['file_type']=='video': await bot.send_video(uid,f['file_id'],caption=caption)
    elif f['file_type']=='document': await bot.send_document(uid,f['file_id'],caption=caption)
    elif f['file_type']=='audio': await bot.send_audio(uid,f['file_id'],caption=caption)
    else: await bot.send_document(uid,f['file_id'],caption=caption)

