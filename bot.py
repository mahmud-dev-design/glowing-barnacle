@dp.message(CommandStart())
async def start(m: Message, state: FSMContext):
    await state.clear()
    uid=m.from_user.id
    existing=db("SELECT user_id FROM users WHERE user_id=:id", {"id":uid}, True)
    if not existing:
        args=(m.text or '').split(maxsplit=1)
        ref=None
        if len(args)>1 and args[1].isdigit() and int(args[1])!=uid:
            ref=int(args[1])
            if not db("SELECT user_id FROM users WHERE user_id=:id", {"id":ref}, True): ref=None
        bonus=int(setting('welcome_bonus','0') or 0)
        db("INSERT INTO users(user_id,username,points,referred_by,joined_at) VALUES (:id,:u,:p,:r,:t)", {"id":uid,"u":m.from_user.username or '',"p":bonus,"r":ref,"t":datetime.now(timezone.utc).isoformat()})
        if ref:
            db("UPDATE users SET points=points+3 WHERE user_id=:id", {"id":ref})
            try: await bot.send_message(ref, f"🎉 New referral joined! +3 points. Your balance: {user_points(ref)}")
            except Exception: pass
    if setting('maintenance','0')=='1' and not is_admin(uid):
        await m.answer("Bot is temporarily under maintenance. Please try again later."); return
    await send_home(m)

def user_points(uid):
    r=db("SELECT points FROM users WHERE user_id=:id", {"id":uid}, True)
    return int(r['points']) if r else 0

async def require_join(uid):
    channels=db("SELECT chat_id,title,invite_url FROM channels", fetch=True, many=True)
    missing=[]
    for c in channels:
        try:
            member=await bot.get_chat_member(c['chat_id'],uid)
            if member.status in ('left','kicked'): missing.append(c)
        except Exception:
            missing.append(c)
    return missing

