def db(sql, params=None, fetch=False, many=False):
    params = params or {}
    with engine.begin() as conn:
        result = conn.execute(text(sql), params)
        if fetch:
            if many:
                return [dict(r._mapping) for r in result.fetchall()]
            row = result.fetchone()
            return dict(row._mapping) if row else None
        return result.rowcount


def init_db():
    statements = [
      "CREATE TABLE IF NOT EXISTS users (user_id BIGINT PRIMARY KEY, username TEXT, points INTEGER NOT NULL DEFAULT 0, referred_by BIGINT, joined_at TEXT NOT NULL)",
      "CREATE TABLE IF NOT EXISTS admins (user_id BIGINT PRIMARY KEY)",
      "CREATE TABLE IF NOT EXISTS files (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', category TEXT NOT NULL DEFAULT 'General', price INTEGER NOT NULL, file_id TEXT NOT NULL, file_type TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1)",
      "CREATE TABLE IF NOT EXISTS packages (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT NOT NULL, points INTEGER NOT NULL, price TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1)",
      "CREATE TABLE IF NOT EXISTS promos (code TEXT PRIMARY KEY, points INTEGER NOT NULL, uses_left INTEGER NOT NULL DEFAULT -1, active INTEGER NOT NULL DEFAULT 1)",
      "CREATE TABLE IF NOT EXISTS channels (chat_id TEXT PRIMARY KEY, title TEXT NOT NULL, invite_url TEXT NOT NULL DEFAULT '')",
      "CREATE TABLE IF NOT EXISTS payments (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL, method TEXT NOT NULL, amount TEXT NOT NULL, reference TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending', points INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL)",
      "CREATE TABLE IF NOT EXISTS purchases (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL, file_id INTEGER NOT NULL, created_at TEXT NOT NULL, UNIQUE(user_id,file_id))",
      "CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL)"
    ]
    # SQLite identity syntax differs; use portable autoincrement declarations on SQLite.
    if engine.dialect.name == "sqlite":
        statements = [s.replace("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT") for s in statements]
    for s in statements:
        db(s)
    db("INSERT INTO admins(user_id) VALUES (:id) ON CONFLICT (user_id) DO NOTHING", {"id": OWNER_ID})
    db("INSERT INTO settings(key,value) VALUES ('welcome_bonus','0') ON CONFLICT (key) DO NOTHING")
    db("INSERT INTO settings(key,value) VALUES ('maintenance','0') ON CONFLICT (key) DO NOTHING")


