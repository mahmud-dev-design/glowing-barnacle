def is_admin(uid):
    return uid == OWNER_ID or bool(db("SELECT user_id FROM admins WHERE user_id=:id", {"id": uid}, True))

def setting(key, default=""):
    r = db("SELECT value FROM settings WHERE key=:k", {"k": key}, True)
    return r["value"] if r else default

def set_setting(key, value):
    db("INSERT INTO settings(key,value) VALUES (:k,:v) ON CONFLICT (key) DO UPDATE SET value=excluded.value", {"k": key, "v": str(value)})

